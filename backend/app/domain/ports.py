"""Ports : contrats que l'infrastructure doit respecter. Le domaine et l'application ne
dépendent que de ces interfaces."""
from __future__ import annotations

from typing import Iterator, Protocol

from .entities import (Chunk, Conversation, Document, LLMResult, Message, Passage, Principal,
                       Usage, User)


class FileLoaderPort(Protocol):
    def load(self, filename: str, data: bytes) -> list[tuple[int, str]]: ...


class ChunkerPort(Protocol):
    def split(self, text: str) -> list[str]: ...


class EmbeddingPort(Protocol):
    def embed_documents(self, texts: list[str]) -> list[list[float]]: ...
    def embed_query(self, text: str) -> list[float]: ...


class VectorStorePort(Protocol):
    def add_document(self, doc: Document) -> Document: ...
    def add_chunks(self, chunks: list[Chunk]) -> None: ...
    def delete_document(self, document_id: int) -> bool: ...
    def get_document(self, document_id: int) -> Document | None: ...
    def find_by_hash(self, sha256: str) -> Document | None: ...
    def find_by_title(self, title: str) -> list[Document]: ...
    def list_documents(self) -> list[Document]: ...
    def get_chunks(self, document_id: int, limit: int = 20) -> list[Passage]: ...
    def search_vector(self, embedding: list[float], k: int,
                      document_ids: list[int] | None = None) -> list[Passage]: ...
    def search_lexical(self, query: str, k: int,
                       document_ids: list[int] | None = None) -> list[Passage]: ...


class RerankerPort(Protocol):
    def rerank(self, query: str, passages: list[Passage], top_n: int) -> list[Passage]: ...


class LLMPort(Protocol):
    def complete(self, system: str, user: str, *, history: list[tuple[str, str]] | None = None,
                 model: str | None = None, json_mode: bool = False) -> LLMResult: ...

    def stream(self, system: str, user: str, *, history: list[tuple[str, str]] | None = None,
               model: str | None = None) -> Iterator[str | Usage]:
        """Produit des morceaux de texte (str) puis, en dernier, un objet Usage."""


class UserRepositoryPort(Protocol):
    def add(self, user: User) -> User: ...
    def get(self, user_id: int) -> User | None: ...
    def get_by_username(self, username: str) -> User | None: ...
    def list(self) -> list[User]: ...
    def count(self) -> int: ...
    def delete(self, user_id: int) -> bool: ...


class ConversationRepositoryPort(Protocol):
    def create(self, user_id: int, title: str) -> Conversation: ...
    def get(self, conversation_id: str, user_id: int) -> Conversation | None: ...
    def list(self, user_id: int) -> list[Conversation]: ...
    def delete(self, conversation_id: str, user_id: int) -> bool: ...
    def add_message(self, conversation_id: str, role: str, content: str,
                    sources: list[dict] | None = None, cited: list[int] | None = None,
                    usage: dict | None = None) -> Message: ...
    def messages(self, conversation_id: str, limit: int | None = None) -> list[Message]: ...
    def set_feedback(self, message_id: int, user_id: int, value: int) -> bool: ...


class UsageRepositoryPort(Protocol):
    def add(self, user_id: int | None, operation: str, usage: Usage) -> None: ...
    def summary(self, user_id: int | None, days: int) -> dict: ...


class PasswordHasherPort(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, hashed: str) -> bool: ...


class TokenServicePort(Protocol):
    def create(self, user: User) -> str: ...
    def decode(self, token: str) -> Principal: ...